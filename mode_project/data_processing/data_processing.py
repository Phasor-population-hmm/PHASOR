def load_stim_json(json_path: str) -> pd.DataFrame:
    with open(json_path) as f:
        con_list = json.load(f)

    stimuli = con_list["stimuli"]

    records = []
    for idx, entry in enumerate(stimuli):

        body = entry.get("bodyMs", 0)
        tail = entry.get("tailMs", 0)

        records.append({
            "stim_index": idx,
            "stimType": entry.get("stimType"),
            "contrast": entry.get("c"),
            "hz": entry.get("hz"),

            # 正确 stimulus duration
            "durationMS": body + tail,
        })

    return pd.DataFrame(records)

