    T = X.shape[0]
    split = int(np.floor(T * (1.0 - test_frac)))
    X_train = X[:split]
    X_test  = X[split:]

    if seeds is None:
        seeds = [0]
    if fit_kwargs is None:
        fit_kwargs = dict(n_iter=30, tol=1e-4, verbose=False)

    out = {}
