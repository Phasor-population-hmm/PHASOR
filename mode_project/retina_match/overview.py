def export_one_pair_results(
    key,
    distance_dict,
    pair_inputs,
    tau,
    global_dmin,
    global_dmax,
    base_dir="/content/drive/MyDrive/upstate/mode_project/matching_results",
    top_n_overview=4,
    bin_ms=10,
    max_reps=4,
    time_window=None,
    allow_many_to_one=True,
):
    nameA, nameB = key
    pair_name = f"{nameA}__vs__{nameB}"

    pair_dir = Path(base_dir) / pair_name
    matched_dir = pair_dir / "matched_pairs"
    unmatched_A_dir = pair_dir / "unmatched_A"
    unmatched_B_dir = pair_dir / "unmatched_B"
    overview_dir = pair_dir / "overview"
    tables_dir = pair_dir / "tables"

    for d in [pair_dir, matched_dir, unmatched_A_dir, unmatched_B_dir, overview_dir, tables_dir]:
        d.mkdir(parents=True, exist_ok=True)

    D = distance_dict[key]
    info = pair_inputs[key]

    # -------- run bidirectional summary --------
    df_AB, df_BA, sim_AB, sim_BA, sim_sym, outs = summarize_retina_matching_true_bidirectional(
        D=D,
        fpA=info["fpA"],
        fpB=info["fpB"],
        tau=tau,
        global_dmin=global_dmin,
        global_dmax=global_dmax,
        pairs_AB=info["pairs_AB"],
        pairs_BA=info["pairs_BA"],
        z_repsA=info["z_repsA"],
        z_repsB=info["z_repsB"],
        allow_many_to_one=allow_many_to_one,
        do_plot=False,   # 这里关掉，不然 notebook 里会爆很多图
    )

    # -------- save overview figure --------
    overview_path = overview_dir / f"{pair_name}_overview.png"
    fig = make_true_bidirectional_matching_overview_figure(
        df_AB=df_AB,
        df_BA=df_BA,
        sim_AB=sim_AB,
        sim_BA=sim_BA,
        sim_sym=sim_sym,
        z_repsA=info["z_repsA"],
        z_repsB=info["z_repsB"],
        top_n=top_n_overview,
        bin_ms=bin_ms,
        time_window=time_window,
        max_reps=max_reps,
        figsize=(18, 12),
        savepath=str(overview_path),
    )
    plt.close(fig)

    # -------- save tables --------
    df_AB.to_csv(tables_dir / f"{pair_name}_A_to_B.csv", index=False)
    df_BA.to_csv(tables_dir / f"{pair_name}_B_to_A.csv", index=False)

    summary_df = pd.DataFrame([{
        "pair": pair_name,
        "tau": tau,
        "global_dmin": global_dmin,
        "global_dmax": global_dmax,
        "A_to_B_matched_quality": sim_AB["matched_pair_score"],
        "A_to_B_coverage": sim_AB["coverage"],
        "A_to_B_overall_similarity": sim_AB["overall_similarity"],
        "B_to_A_matched_quality": sim_BA["matched_pair_score"],
        "B_to_A_coverage": sim_BA["coverage"],
        "B_to_A_overall_similarity": sim_BA["overall_similarity"],
        "symmetric_similarity": sim_sym,
        "method_AB": outs["AB"]["method"],
        "method_BA": outs["BA"]["method"],
    }])
    summary_df.to_csv(tables_dir / f"{pair_name}_summary.csv", index=False)

    with open(tables_dir / f"{pair_name}_summary.txt", "w") as f:
        f.write(f"pair: {pair_name}\n")
        f.write(f"tau: {tau:.6f}\n")
        f.write(f"global_dmin: {global_dmin:.6f}\n")
        f.write(f"global_dmax: {global_dmax:.6f}\n\n")

        f.write("[A -> B]\n")
        f.write(f"matched_pair_score: {sim_AB['matched_pair_score']:.6f}\n")
        f.write(f"coverage: {sim_AB['coverage']:.6f}\n")
        f.write(f"overall_similarity: {sim_AB['overall_similarity']:.6f}\n\n")

        f.write("[B -> A]\n")
        f.write(f"matched_pair_score: {sim_BA['matched_pair_score']:.6f}\n")
        f.write(f"coverage: {sim_BA['coverage']:.6f}\n")
        f.write(f"overall_similarity: {sim_BA['overall_similarity']:.6f}\n\n")

        f.write("[Symmetric]\n")
        f.write(f"symmetric_similarity: {sim_sym:.6f}\n\n")

        f.write("[Methods]\n")
        f.write(f"AB method: {outs['AB']['method']}\n")
        f.write(f"BA method: {outs['BA']['method']}\n")
        f.write(f"AB diag: {outs['AB']['diag']}\n")
        f.write(f"BA diag: {outs['BA']['diag']}\n")

    # -------- matched pairs: use union of AB and BA --------
    matched_AB_full = df_AB[df_AB["A_state"].notna() & df_AB["B_state"].notna()].copy()
    matched_BA_full = df_BA[df_BA["A_state"].notna() & df_BA["B_state"].notna()].copy()

    if len(matched_AB_full):
        matched_AB_full["A_state"] = matched_AB_full["A_state"].astype(int)
        matched_AB_full["B_state"] = matched_AB_full["B_state"].astype(int)
        matched_AB_full["seen_in"] = "AtoB"

    if len(matched_BA_full):
        matched_BA_full["A_state"] = matched_BA_full["A_state"].astype(int)
        matched_BA_full["B_state"] = matched_BA_full["B_state"].astype(int)
        matched_BA_full["seen_in"] = "BtoA"

    tab_union = pd.concat([matched_AB_full, matched_BA_full], axis=0, ignore_index=True)

    if len(tab_union):
        tab_union = (
            tab_union.groupby(["A_state", "B_state"], as_index=False)
            .agg({
                "seen_in": lambda s: "/".join(sorted(set(s))),
                "match_dist": "min",
                "dist_norm_global": "max",
                "dist_sim_global": "max",
                "pair_score": "max",
                "A_occ": "max",
                "B_occ": "max",
                "pair_weight": "max",
            })
            .sort_values(["pair_score", "pair_weight"], ascending=False)
        )

        tab_union.to_csv(tables_dir / f"{pair_name}_matched_union.csv", index=False)

        for _, row in tab_union.iterrows():
            a_state = int(row["A_state"])
            b_state = int(row["B_state"])
            seen_in = str(row["seen_in"]).replace("/", "-")

            savepath = matched_dir / (
                f"A_s{a_state:02d}__B_s{b_state:02d}__"
                f"sim_{row['pair_score']:.3f}__{seen_in}.png"
            )

            save_matched_pair_figure(
                a_state=a_state,
                b_state=b_state,
                row=row,
                z_repsA=info["z_repsA"],
                z_repsB=info["z_repsB"],
                savepath=str(savepath),
                bin_ms=bin_ms,
                max_reps=max_reps,
                time_window=time_window,
            )

    # -------- unmatched A --------
    unmatched_A = df_AB[df_AB["A_state"].notna() & df_AB["B_state"].isna()].copy()
    if len(unmatched_A):
        unmatched_A["A_state"] = unmatched_A["A_state"].astype(int)
        unmatched_A = unmatched_A.sort_values("A_occ", ascending=False)
        unmatched_A.to_csv(tables_dir / f"{pair_name}_unmatched_A.csv", index=False)

        for _, row in unmatched_A.iterrows():
            a_state = int(row["A_state"])
            occ = float(row["A_occ"])
            savepath = unmatched_A_dir / f"A_s{a_state:02d}__occ_{occ:.3f}.png"
            save_unmatched_state_figure(
                state=a_state,
                side="A",
                occ=occ,
                z_reps=info["z_repsA"],
                savepath=str(savepath),
                bin_ms=bin_ms,
                max_reps=max_reps,
                time_window=time_window,
            )

    # -------- unmatched B --------
    unmatched_B = df_BA[df_BA["A_state"].isna() & df_BA["B_state"].notna()].copy()
    if len(unmatched_B):
        unmatched_B["B_state"] = unmatched_B["B_state"].astype(int)
        unmatched_B = unmatched_B.sort_values("B_occ", ascending=False)
